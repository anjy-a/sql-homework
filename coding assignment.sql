CREATE TABLE grocery_items (
    item_id NUMBER (5) PRIMARY KEY,
    item_name VARCHAR2(50),
    category VARCHAR(50),
    quantity INT,
    price NUMBER (10,2),
    weight FLOAT,
    date_added DATE,
    expiration_date DATE
);

